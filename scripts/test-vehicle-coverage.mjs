import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { buildCoverage } from '../functions/vehicles/_coverage.js';
import { isLive, modelLinks, renderVehiclePage } from '../functions/vehicles/_render.js';
import { onRequest } from '../functions/enquire.js';
const read = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const register = await read('../functions/_data/data.json');
const editorial = await read('../functions/_data/vehicle-pages.json');
const coverage = buildCoverage(register, editorial.pages);
assert.equal(coverage.matched_records + coverage.candidate_records, register.sev.length + register.mre.length);
assert.equal(new Set(coverage.pages.map(p => p.slug)).size, coverage.pages.length);
assert.ok(coverage.pages.every(p => !isLive(p) && p.approvals.length === 0));
assert.ok(!isLive({...coverage.pages[0],publish_ready:true,reviewed_by:'accidental flag'}));
const saved = await read('../functions/_data/vehicle-coverage.json');
const decisions = await read('../docs/evidence/coverage-decisions-20260908.json');
for (const page of saved.pages) {
  const decision = decisions.find(d=>d.candidate===page.slug && d.decision==='hold');
  if (decision) assert.deepEqual(page.review_note,{date:'2026-09-08',reasons:decision.reasons});
  else assert.equal(page.review_note,undefined);
  delete page.review_note;
}
assert.deepEqual(coverage, saved);
const draft = coverage.pages[0];
const rendered = await renderVehiclePage(draft, coverage.generated_at).text();
assert.match(rendered, /Eligibility not yet verified/);
assert.match(rendered, /noindex/);
assert.doesNotMatch(rendered, /Nothing on the register for this model/);
assert.match(rendered, /Original register records/);
const links = modelLinks(editorial.pages);
for (const page of editorial.pages.filter(p => !isLive(p))) assert.ok(!links.includes(`/vehicles/${page.slug}`));
assert.match(links, /href="\/vehicles"/);
const hostile = await onRequest({request: new Request('https://importcheck.com.au/enquire?vehicle=' + encodeURIComponent('<script>alert(1)</script>'))}).text();
assert.ok(!hostile.includes('<script>alert(1)</script>'));
assert.ok(hostile.includes('&lt;script&gt;'));
assert.match(hostile, /imports@jdmconnect.com.au/);
assert.match(hostile, /0gQCujDNgaGlG83rK10j/);
assert.match(hostile, /tell_us_what_you%27re_after=/);
assert.doesNotMatch(hostile, /Draft.*not signed off/);
const row = {Make:'TEST',Model:'MODEL','SEV #':'SEV-1'};
const known = {slug:'test-model',make_norm:'TEST',canonical_name:'Test Model',aka_names:[],approvals:[]};
assert.equal(buildCoverage({sev:[row],mre:[]},[known]).pages.length,0);
assert.equal(buildCoverage({sev:[row],mre:[]},[known,{...known,slug:'ambiguous'}]).pages.length,1);
assert.equal(buildCoverage({sev:[{...row,Make:''}],mre:[]},[]).pages.length,1);
const live = editorial.pages.find(isLive);
const dated = await renderVehiclePage({...live, approvals:[{scheme:'SEV',approval_number:'SEV-TEST',status:'eligible',build_from:'2010-01-01',build_to:'2012-12-01',build_open:false}]},editorial.generated_at).text();
assert.match(dated, /Jan 2010 to Dec 2012/);
console.log(`Coverage and enquiry checks passed: all ${register.sev.length + register.mre.length} records accounted for, ${coverage.pages.length} review candidates.`);
